-- Hearthstone addon: reusable card widget.
--
-- One widget shows one card: the pre-rendered card texture when it is installed, otherwise a
-- readable text fallback (cost, name, type, rules text, attack/health) so a missing texture
-- never shows up as a green box. The same widget is used for the 8 grid slots and the enlarged
-- hover preview.
--
--   local w = H.CardWidget.Create(parent, name, width, big)   -- width 146 for a slot, 256 for full size
--   H.CardWidget.SetCard(w, id [, forceTexture])               -- id nil clears it
--   H.CardWidget.SetDimmed(w, dimmed)                           -- greyed out (card not owned)
--   w.frame                                                     -- position it with w.frame:SetPoint(...)
--
-- The texture path and the texcoord (the card sits in the top part of a 256x512 texture) are
-- defined here; CardTextures.lua (generated by the deploy script) supplies the per-card overrides.
-- Lua 5.0 / WoW 1.12.

Hearthstone = Hearthstone or {}
local H = Hearthstone
H.CardWidget = H.CardWidget or {}
local W = H.CardWidget

H.CARD_TEXTURE_PATH = "Interface\\AddOns\\Hearthstone\\Textures\\Cards\\"
H.CARD_DEFAULT_BOTTOM = 388 / 512    -- the BLP canvas is 256x512, the card sits at the top

-- Bottom texture coordinate of a card: from CardTextures.lua, else 388/512.
function H.CardBottom(id)
    local t = HS_CardTextures
    if type(t) == "table" and type(t.bottom) == "table" and type(t.bottom[id]) == "number" then
        return t.bottom[id]
    end
    return H.CARD_DEFAULT_BOTTOM
end

W.CARD_ASPECT = 388 / 256

-- The visible card inside the 256 x 388 render. The render has a transparent margin around the card (the
-- texture is 256 x 512 on top of that), so a frame, glow or banner attached to the widget's edge hangs
-- off the card. These numbers come from the used area (alpha > 40) of all 382 collectible card renders:
-- x 9 ... 240 (the body is 10 ... 236), y 18 ... 347 (the body starts at 32; only Legendary dragons and
-- the like reach above it) and the bottom edge is 341 ... 347 for every collectible card. Hero cards are
-- a little lower (53 ... 363) and are not shown in the collection.
W.VISIBLE = { left = 10, top = 30, right = 236, bottom = 347 }       -- pixels of the 256 x 388 render

-- The visible card of a widget of the given width as pixels from the widget's top left corner:
-- left, top, right, bottom (right and bottom are the card's own edges, not widths).
function W.VisibleRect(width)
    local s = width / 256
    local v = W.VISIBLE
    return v.left * s, v.top * s, v.right * s, v.bottom * s
end

local WHITE = "Interface\\Buttons\\WHITE8X8"
local TOOLTIP_EDGE = "Interface\\Tooltips\\UI-Tooltip-Border"

-- Fallback background colour per class (dark, readable text on top).
local CLASS_BG = {
    DRUID = { 0.24, 0.16, 0.06 }, HUNTER = { 0.10, 0.20, 0.08 }, MAGE = { 0.08, 0.14, 0.26 },
    PALADIN = { 0.26, 0.20, 0.10 }, PRIEST = { 0.22, 0.22, 0.22 }, ROGUE = { 0.20, 0.20, 0.08 },
    SHAMAN = { 0.06, 0.14, 0.24 }, WARLOCK = { 0.18, 0.08, 0.22 }, WARRIOR = { 0.24, 0.08, 0.08 },
    NEUTRAL = { 0.16, 0.13, 0.09 },
}

local function newFS(parent, font, justify)
    local fs = parent:CreateFontString(nil, "OVERLAY", font)
    fs:SetJustifyH(justify or "LEFT")
    return fs
end

-- Creates a widget of the given width (height follows the 256x388 aspect ratio).
-- 'big' selects the larger fonts of the full size card.
function W.Create(parent, name, width, big)
    local height = math.floor(width * W.CARD_ASPECT + 0.5)
    local sx = width / 256
    local f = CreateFrame("Frame", name, parent)
    f:SetWidth(width)
    f:SetHeight(height)

    local w = { frame = f, width = width, height = height, big = big and true or false, id = nil, texId = nil }

    local tex = f:CreateTexture(nil, "ARTWORK")
    tex:SetAllPoints(f)
    w.tex = tex

    -- text fallback, hidden while the texture is shown
    local fb = CreateFrame("Frame", nil, f)
    fb:SetAllPoints(f)
    fb:SetBackdrop({
        edgeFile = TOOLTIP_EDGE, edgeSize = 12,
        insets = { left = 3, right = 3, top = 3, bottom = 3 },
    })
    local bg = fb:CreateTexture(nil, "BACKGROUND")
    bg:SetTexture(WHITE)
    bg:SetPoint("TOPLEFT", fb, "TOPLEFT", 3, -3)
    bg:SetPoint("BOTTOMRIGHT", fb, "BOTTOMRIGHT", -3, 3)
    bg:SetVertexColor(0.16, 0.13, 0.09)
    w.fb = fb
    w.bg = bg

    local bigFont = w.big
    local cost = newFS(fb, "GameFontNormalLarge", "CENTER")
    cost:SetPoint("TOPLEFT", fb, "TOPLEFT", 6 * sx, -8 * sx)
    cost:SetWidth(30 * sx)
    w.cost = cost

    local nm = newFS(fb, bigFont and "GameFontNormalLarge" or "GameFontNormal", "LEFT")
    nm:SetPoint("TOPLEFT", fb, "TOPLEFT", 40 * sx, -10 * sx)
    nm:SetWidth(width - 48 * sx)
    nm:SetHeight(bigFont and 40 or 28)
    w.name = nm

    local ty = newFS(fb, "GameFontDisableSmall", "LEFT")
    ty:SetPoint("TOPLEFT", fb, "TOPLEFT", 10 * sx, -(bigFont and 58 or 44) * sx)
    ty:SetWidth(width - 20 * sx)
    ty:SetHeight(12)
    w.typeLine = ty

    local tx = newFS(fb, bigFont and "GameFontHighlight" or "GameFontHighlightSmall", "CENTER")
    local top = (bigFont and 84 or 64) * sx
    tx:SetPoint("TOPLEFT", fb, "TOPLEFT", 12 * sx, -top)
    tx:SetWidth(width - 24 * sx)
    tx:SetHeight(height - top - 36 * sx)
    tx:SetJustifyV("TOP")
    w.text = tx

    local st = newFS(fb, bigFont and "GameFontNormalLarge" or "GameFontNormal", "CENTER")
    st:SetPoint("BOTTOM", fb, "BOTTOM", 0, 10 * sx)
    st:SetWidth(width - 24 * sx)
    w.stats = st

    fb:Hide()
    tex:Hide()
    return w
end

local function showFallback(w, id, card)
    local info = HsCollection.FallbackInfo(id, card)
    local c = CLASS_BG[info.class or "NEUTRAL"] or CLASS_BG.NEUTRAL
    w.bg:SetVertexColor(c[1], c[2], c[3])
    if info.cost ~= "" then
        w.cost:SetText("|cff55aaff" .. info.cost .. "|r")
    else
        w.cost:SetText("")
    end
    w.name:SetText((info.color or "|cffffffff") .. info.name .. "|r")
    w.typeLine:SetText(info.typeLine)
    w.text:SetText(info.text)
    if info.stats ~= "" then
        w.stats:SetText("|cffffd100" .. info.stats .. "|r")
    else
        w.stats:SetText("")
    end
    w.tex:Hide()
    w.fb:Show()
end

-- Tilts the card texture by 'angle' radians (clockwise on screen; 0 or nil: upright) around the middle of the card.
-- The 1.12 client has no texture rotation except the 8-value texcoord form, and one axis-aligned quad around a tilted
-- card would sample far outside the card's 256 x 512 render at the quad's corners. So a tilted card is drawn as
-- W.TILT_STRIPS thin horizontal strips: each strip is only as wide as the tilted card is inside its band, and its four
-- corners sample the source turned back by the angle, so every sample stays inside the render (at most a few pixels
-- outside the card's outline, in its transparent margin; the top strips may reach about 15 px above the render, which is the empty bottom of the
-- texture if the client wraps and the empty top row if it clamps). The text fallback cannot tilt and stays upright. Gems and
-- glow are not part of the texture: the caller moves them (W.TiltPoint).
W.TILT_STRIPS = 12
W.TILT_SRC = { left = 8, top = 16, right = 244, bottom = 349 }   -- the card incl. the widest art, in the 256 x 388 render

function W.SetTilt(w, angle)
    w.tilt = angle
    W.ApplyTilt(w)
end

local function hideStrips(w)
    if w.strips then
        for i = 1, table.getn(w.strips) do
            w.strips[i].tex:Hide()
        end
    end
end

-- x range of the polygon (4 points, screen y down) inside the band y0 .. y1
local function bandRange(poly, y0, y1)
    local lo, hi = nil, nil
    local function add(x)
        if not lo or x < lo then lo = x end
        if not hi or x > hi then hi = x end
    end
    local n = table.getn(poly)
    for i = 1, n do
        local nx = i + 1
        if nx > n then
            nx = 1
        end
        local a, b = poly[i], poly[nx]
        if a[2] >= y0 and a[2] <= y1 then add(a[1]) end
        local ys = { y0, y1 }
        for k = 1, 2 do
            local y = ys[k]
            if (a[2] - y) * (b[2] - y) < 0 then
                add(a[1] + (b[1] - a[1]) * (y - a[2]) / (b[2] - a[2]))
            end
        end
    end
    return lo, hi
end

-- Draws a tilted rectangle as horizontal strips on 'frame' (the core of the card tilt, also used for the hand glow).
--   list   the strips: a table that keeps { tex, path } entries (created here, reused on the next call)
--   rect   the untilted rectangle in frame pixels from the frame's top left: { l, t, r, b }
--   px, py the pivot it turns around (frame pixels)
--   map    how a source offset (sx, sy) from the pivot becomes a texture coordinate: u = a + b * sx, v = c + d * sy
--   angle  radians, clockwise on screen;  n  the number of strips;  init(tex)  runs once per new strip
-- The strips cover the tilted rectangle exactly (each only as wide as the rectangle is inside its band); the corners
-- of every strip sample the source turned back by the angle.
function W.PlaceStrips(list, frame, layer, path, rect, px, py, map, angle, n, init)
    local c, sn = math.cos(angle), math.sin(angle)
    local hw, hh = (rect.r - rect.l) / 2, (rect.b - rect.t) / 2
    local mx, my = (rect.l + rect.r) / 2 - px, (rect.t + rect.b) / 2 - py     -- the rectangle's centre from the pivot
    local poly = {}
    local corners = { { -hw, -hh }, { hw, -hh }, { hw, hh }, { -hw, hh } }
    local ymin, ymax = nil, nil
    for i = 1, 4 do
        local x, y = corners[i][1] + mx, corners[i][2] + my
        poly[i] = { x * c - y * sn, x * sn + y * c }
        if not ymin or poly[i][2] < ymin then ymin = poly[i][2] end
        if not ymax or poly[i][2] > ymax then ymax = poly[i][2] end
    end
    local function uv(ox, oy)
        -- the screen point (ox, oy) from the pivot shows the source point turned back by the angle
        local sx, sy = ox * c + oy * sn, -ox * sn + oy * c
        return map.a + map.b * sx, map.c + map.d * sy
    end
    for j = 1, n do
        local st = list[j]
        if not st then
            st = { tex = frame:CreateTexture(nil, layer) }
            if init then
                init(st.tex)
            end
            list[j] = st
        end
        local y0 = ymin + (j - 1) * (ymax - ymin) / n
        local y1 = ymin + j * (ymax - ymin) / n
        local lo, hi = bandRange(poly, y0, y1)
        local t = st.tex
        if lo then
            if st.path ~= path then
                t:SetTexture(path)
                st.path = path
            end
            t:ClearAllPoints()
            t:SetPoint("TOPLEFT", frame, "TOPLEFT", px + lo, -(py + y0))
            t:SetWidth(hi - lo)
            t:SetHeight(y1 - y0)
            local u1, v1 = uv(lo, y0)
            local u2, v2 = uv(lo, y1)
            local u3, v3 = uv(hi, y0)
            local u4, v4 = uv(hi, y1)
            t:SetTexCoord(u1, v1, u2, v2, u3, v3, u4, v4)
            t:Show()
        else
            t:Hide()
        end
    end
    for j = n + 1, table.getn(list) do
        list[j].tex:Hide()
    end
end

function W.HideStrips(list)
    for i = 1, table.getn(list or {}) do
        list[i].tex:Hide()
    end
end

function W.ApplyTilt(w)
    local tex = w.tex
    local angle = w.tilt
    local bottom = w.bottom or 388 / 512
    if not angle or angle == 0 or not w.usingTexture then
        hideStrips(w)
        tex:ClearAllPoints()
        tex:SetAllPoints(w.frame)
        tex:SetTexCoord(0, 1, 0, bottom)
        if w.tilted and w.usingTexture then
            tex:Show()
        end
        w.tilted = false
        return
    end
    local width, height = w.width, w.height
    local k = width / 256
    local src = W.TILT_SRC
    local rect = { l = src.left * k, t = src.top * k, r = src.right * k, b = src.bottom * k }
    local px, py = (rect.l + rect.r) / 2, (rect.t + rect.b) / 2      -- pivot: the middle of the card
    local path = (H.CARD_TEXTURE_PATH or "Interface\\AddOns\\Hearthstone\\Textures\\Cards\\") .. tostring(w.id)
    w.strips = w.strips or {}
    tex:Hide()
    W.PlaceStrips(w.strips, w.frame, "ARTWORK", path, rect, px, py,
        { a = px / width, b = 1 / width, c = py / height * bottom, d = bottom / height }, angle, W.TILT_STRIPS)
    w.tilted = true
end

-- The point (x, y), measured from the card's middle (x right, y up), after the card tilted clockwise by 'angle'.
function W.TiltPoint(x, y, angle)
    if not angle or angle == 0 then
        return x, y
    end
    local c, s = math.cos(angle), math.sin(angle)
    return x * c + y * s, -x * s + y * c
end

-- Shows card 'id' (a CardDB id) in the widget. forceTexture tries the texture even when
-- CardTextures.lua does not list it. Never raises on unknown ids.
function W.SetCard(w, id, forceTexture)
    w.id = id
    if id == nil then
        w.tex:Hide()
        w.fb:Hide()
        w.usingTexture = false
        hideStrips(w)
        return
    end
    local db = HsCollection.GetDB()
    local card = nil
    if db then
        card = db.cards[id]
    end
    if forceTexture or HsCollection.HasTexture(id) then
        local bottom = 388 / 512
        if H.CardBottom then
            bottom = H.CardBottom(id)
        end
        if w.texId ~= id then
            w.tex:SetTexture((H.CARD_TEXTURE_PATH or "Interface\\AddOns\\Hearthstone\\Textures\\Cards\\") .. id)
            w.texId = id
        end
        w.bottom = bottom
        w.tex:SetTexCoord(0, 1, 0, bottom)
        w.tex:Show()
        w.fb:Hide()
        w.usingTexture = true
        if w.tilt or w.tilted then
            W.ApplyTilt(w)
        end
    else
        showFallback(w, id, card)
        w.usingTexture = false
        if w.tilt or w.tilted then
            W.ApplyTilt(w)
        end
    end
end

-- Greys the card out (a card the player does not own) or restores it. Texture:SetDesaturated is
-- used when the client has it and says it worked (it returns nil without shader support); the
-- darker vertex colour and the lower alpha of the whole widget (which also covers the text
-- fallback) work on every 1.12 client, so the card is visibly dimmed either way.
W.DIM_ALPHA = 0.6
W.DIM_SHADE = 0.6

function W.SetDimmed(w, dimmed)
    local tex = w.tex
    local desat = nil
    if tex.SetDesaturated then
        if dimmed then
            desat = tex:SetDesaturated(1)
        else
            tex:SetDesaturated(nil)
        end
    end
    if w.strips then
        local shade = dimmed and W.DIM_SHADE or 1
        for i = 1, table.getn(w.strips) do
            w.strips[i].tex:SetVertexColor(shade, shade, shade)
        end
    end
    if dimmed then
        tex:SetVertexColor(W.DIM_SHADE, W.DIM_SHADE, W.DIM_SHADE)
        w.frame:SetAlpha(W.DIM_ALPHA)
    else
        tex:SetVertexColor(1, 1, 1)
        w.frame:SetAlpha(1)
    end
    w.dimmed = dimmed and true or false
    w.desaturated = desat and true or false
end
