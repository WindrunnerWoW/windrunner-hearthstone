    struct Settings
    {
        bool enable = true;
        bool debug = false;
        uint32_t maxInboundBytes = 4096;
        uint32_t maxInboundParts = 16;
        uint32_t reassemblyTimeoutMs = 10000;
        uint32_t maxPendingRequests = 4;
        uint32_t ratePerSecond = 10;
        uint32_t rateBurst = 30;
        uint32_t matchAuraSpellId = 0; // Hearthstone.MatchAuraSpellId (0: matches start without the effect)
        bool matchEnable = true;       // Hearthstone.Match.Enable: WELCOME lists the "match" capability
        // The Warsong Battlegrounds payout in coins: every finished game pays the base (a loss as much as a duel win),
        // the winning faction pays the team amount instead, and first place pays the first amount instead of both (the
        // amounts are totals, they never stack). Packs come from the Battlegrounds weeklies. Every value is a config
        // key, so the payout changes without a rebuild.
        int bgRewardBase = 3;
        int bgRewardTeam = 5;
        int bgRewardFirst = 7;
        // The honor of a finished game, on the same shape as the coins (totals, never added): the faction war pays honor.
        int bgHonorBase = 10;
        int bgHonorTeam = 50;
        int bgHonorFirst = 70;
    };

    // Clamps every value into a sane range (configs are user input).
    Settings Sanitize(Settings s);

    struct ServerInfo
    {
        std::string moduleVersion;
        std::string datasetId;
        std::string datasetHash; // empty -> "-"
        // "1" when a character of the account turned in the introduction's card quest (919703 / 919713),
        // "0" when not; empty = not sent. WELCOME carries it as intro=; the addon shows its micro menu button only then.
        std::string intro;
        // The arena is available (tables, card data and matches ready): WELCOME lists the "arena" capability.
        bool arena = false;
        // Reward track: the portrait tables exist (character migration 0021): WELCOME lists "heroes".
        bool heroes = false;
    };

