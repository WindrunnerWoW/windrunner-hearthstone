#!/usr/bin/env python3
"""Regenerate src/HsDataset.h from data/cards/cards.normalized.json.

Usage (from the module root):
    python scripts/gen_dataset_header.py           # rewrite src/HsDataset.h
    python scripts/gen_dataset_header.py --check   # exit 1 if the header is stale

Only reads the dataset file; never modifies it.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "cards", "cards.normalized.json")
OUT = os.path.join(ROOT, "src", "HsDataset.h")
WIRE_HASH_CHARS = 16


def render():
    with open(SRC, "r", encoding="utf-8") as fh:
        data = json.load(fh)
    dataset_id = data["dataset_id"]
    content_hash = data["content_hash"]
    count = data["card_count"]
    return f"""/*
 * GENERATED by scripts/gen_dataset_header.py from data/cards/cards.normalized.json.
 * Do not edit by hand; rerun the script after the card dataset changes.
 */

#ifndef MOD_HEARTHSTONE_HS_DATASET_H
#define MOD_HEARTHSTONE_HS_DATASET_H

namespace Hs
{{
    constexpr char const* kDatasetId = "{dataset_id}";
    // First {WIRE_HASH_CHARS} hex characters of the dataset content_hash (what goes on the wire).
    constexpr char const* kDatasetHash = "{content_hash[:WIRE_HASH_CHARS]}";
    // Full content_hash, for logs and .hs status.
    constexpr char const* kDatasetHashFull = "{content_hash}";
    constexpr unsigned kDatasetCardCount = {count}u;
}}

#endif
"""


def main():
    text = render()
    if "--check" in sys.argv:
        try:
            with open(OUT, "r", encoding="utf-8", newline="") as fh:
                current = fh.read()
        except OSError:
            current = ""
        if current.replace("\r\n", "\n") != text:
            print("src/HsDataset.h is stale")
            return 1
        print("src/HsDataset.h is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
