"""Writes tests/match_all_cards.h and tests/card_catalog.h: every card of data/cards/cards.normalized.json as a Hs::Match::CardDef
row, for the card tests. Rerun after the dataset changes: python tests/gen_all_cards.py"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def cstr(s):
    s = s or ""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "") + '"'


def main():
    data = json.load(open(os.path.join(ROOT, "data", "cards", "cards.normalized.json"), encoding="utf-8"))
    rows = []
    for c in sorted(data["cards"], key=lambda c: c["id"]):
        rows.append("        {%s, %s, %s, %s, %s, %s, %d, %d, %d, %d, %d, %d, %s, %s}," % (
            cstr(c["id"]), cstr(c["name"]), cstr(c["class"]), cstr(c.get("rarity")), cstr(c.get("race")),
            cstr(c["type"]), c.get("cost") or 0, c.get("attack") or 0, c.get("health") or 0,
            c.get("durability") or 0, c.get("spell_damage") or 0, c.get("overload") or 0,
            cstr(",".join(c.get("mechanics") or [])), cstr(c.get("text"))))
    out = """// GENERATED by tests/gen_all_cards.py from data/cards/cards.normalized.json (%s, %d cards).
// Do not edit by hand. Every card of the dataset as the engine sees it (the glue loads the same columns
// from hearthstone_card_template).

#ifndef MOD_HEARTHSTONE_MATCH_ALL_CARDS_H
#define MOD_HEARTHSTONE_MATCH_ALL_CARDS_H

#include "../src/match/HsMatch.h"

namespace MatchAllCards
{
    struct Row
    {
        char const* id;
        char const* name;
        char const* cls;
        char const* rarity;
        char const* race;
        char const* type;
        int cost, attack, health, durability, spellDamage, overload;
        char const* mechanics;
        char const* text;
    };

    // clang-format off
    static Row const kRows[] = {
%s
    };
    // clang-format on

    inline Hs::Match::CardDb const& Db()
    {
        static Hs::Match::CardDb const db = []() {
            Hs::Match::CardDb d;
            for (Row const& r : kRows)
            {
                Hs::Match::CardDef def;
                def.id = r.id;
                def.name = r.name;
                def.cardClass = r.cls;
                def.rarity = r.rarity;
                def.race = r.race;
                def.text = r.text;
                def.type = Hs::Match::ParseCardType(r.type);
                def.cost = r.cost;
                def.attack = r.attack;
                def.health = r.health;
                def.durability = r.durability;
                def.spellDamage = r.spellDamage;
                def.overload = r.overload;
                Hs::Match::ApplyMechanics(r.mechanics, def);
                d.Add(def);
            }
            return d;
        }();
        return db;
    }
}

#endif
""" % (data["dataset_id"], len(rows), "\n".join(rows))
    open(os.path.join(HERE, "match_all_cards.h"), "w", encoding="utf-8", newline="\n").write(out)

    # The catalog columns the compatibility report needs, kept apart from the CardDef rows.
    cat = []
    for c in sorted(data["cards"], key=lambda c: c["id"]):
        cat.append("        {%s, %s, %d, %s}," % (cstr(c["id"]), cstr(c.get("set")), 1 if c.get("collectible") else 0,
                                                 cstr(c.get("acquisition"))))
    out = """// GENERATED by tests/gen_all_cards.py from data/cards/cards.normalized.json (%s, %d cards).
// Do not edit by hand. Set, collectible flag and acquisition of every card (compatibility report).

#ifndef MOD_HEARTHSTONE_CARD_CATALOG_H
#define MOD_HEARTHSTONE_CARD_CATALOG_H

namespace CardCatalog
{
    struct Row
    {
        char const* id;
        char const* set;         // CORE, EXPERT1, PROMO, ...
        int collectible;         // 1 = collectible
        char const* acquisition; // standard, reward_only, unreleased, none
    };

    // clang-format off
    static Row const kRows[] = {
%s
    };
    // clang-format on
}

#endif
""" % (data["dataset_id"], len(cat), "\n".join(cat))
    open(os.path.join(HERE, "card_catalog.h"), "w", encoding="utf-8", newline="\n").write(out)


if __name__ == "__main__":
    main()
