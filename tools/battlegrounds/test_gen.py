#!/usr/bin/env python3
"""Tests for the C++ card table generator (gen_bg_cpp.py).

Run from the repository root with either:
    python -I -m unittest discover -s tools/battlegrounds -v
    python -I tools/battlegrounds/test_gen.py

The tests on the real dataset are skipped when data/battlegrounds/bg.normalized.json is missing (it is git-ignored:
python -I tools/battlegrounds/import_bg.py rebuilds it).
"""

from __future__ import annotations

import contextlib
import io
import re
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bglib  # noqa: E402
import gen_bg_cpp as gen  # noqa: E402


def card(card_id, **kw):
    """A minimal pool minion record."""
    rec = {"id": card_id, "dbf_id": 1, "name": "Name", "role": "pool_minion", "type": "MINION", "slice": "15A",
           "tier": 2, "attack": 3, "health": 4, "tribes": [], "mechanics": [], "text": None,
           "golden": {"id": card_id + "_G", "dbf_id": 2, "attack": 6, "health": 8, "mechanics": [], "text": None}}
    rec.update(kw)
    return rec


def dataset(*cards):
    return {"dataset_id": "test", "content_hash": "0" * 64, "cards": list(cards)}


class Rows(unittest.TestCase):
    def test_plain_row(self):
        row = gen.row_for(card("X1"))
        self.assertEqual(row, '        {"X1", 1, 2, 3, 4, 0, 0, "X1_G", 2, 6, 8, 0, true, CardRole::Pool},')

    def test_tribes_and_keywords(self):
        row = gen.row_for(card("X2", tribes=["MECHANICAL", "BEAST"], mechanics=["TAUNT", "MODULAR", "DIVINE_SHIELD",
                                                                              "BATTLECRY", "TRIGGER_VISUAL"]))
        self.assertIn("kTribeBeast | kTribeMech, kKwTaunt | kKwDivineShield | kKwMagnetic,", row)
        self.assertNotIn("BATTLECRY", row)

    def test_all_tribe(self):
        self.assertIn(", kTribeAll, 0,", gen.row_for(card("X3", tribes=["ALL"])))

    def test_golden_windfury_is_mega(self):
        c = card("X4", mechanics=["WINDFURY"], text="<b>Windfury</b>")
        c["golden"].update(mechanics=["WINDFURY"], text="<b>Mega-Windfury</b>")
        row = gen.row_for(c)
        self.assertIn(", kKwWindfury, ", row)
        self.assertTrue(row.count("kKwMegaWindfury") == 1 and "kKwMegaWindfury, true" in row)

    def test_golden_windfury_gained_by_the_golden_only(self):
        c = card("X5")
        c["golden"].update(mechanics=["WINDFURY"], text="<b>Mega-Windfury</b>")
        row = gen.row_for(c)
        self.assertIn(", 0, 0, \"X5_G\", 2, 6, 8, kKwMegaWindfury, true", row)

    def test_golden_windfury_without_mega_text_stays_windfury(self):
        # a render override can keep a golden Windfury (Zapp Slywick, data/battlegrounds/render_overrides.json)
        c = card("X6")
        c["golden"].update(mechanics=["WINDFURY"], text="<b>Windfury</b>")
        row = gen.row_for(c)
        self.assertNotIn("kKwMegaWindfury", row)
        self.assertIn("kKwWindfury, true", row)

    def test_venomous(self):
        c = card("X7")
        c.update(mechanics=["VENOMOUS"], text="<b>Venomous</b>")
        self.assertIn("kKwVenomous", gen.row_for(c))

    def test_leading_text_keywords(self):
        # Sparring Partner style: Taunt is only in the text; a Taunt later in the text is not a keyword of the card
        self.assertEqual(gen.text_keywords("<b>Taunt</b>\n<b>Battlecry:</b> Give a minion <b>Taunt</b>."), ["TAUNT"])
        self.assertEqual(gen.text_keywords("[x]<b>Divine Shield</b>\nWhenever you summon"), ["DIVINE_SHIELD"])
        self.assertEqual(gen.text_keywords("<b>Deathrattle:</b> Summon a 2/3 Turtle with <b>Taunt</b>."), [])
        self.assertEqual(gen.text_keywords("<b>Taunt</b>, <b>Reborn</b>"), ["TAUNT", "REBORN"])
        self.assertEqual(gen.text_keywords(None), [])
        row = gen.row_for(card("X7", text="<b>Taunt</b>"))
        self.assertIn(", 0, kKwTaunt, ", row)

    def test_no_golden(self):
        row = gen.row_for(card("X8", role="token", golden=None))
        self.assertIn('0, 0, "", 0, 0, 0, 0, true, CardRole::Token}', row)

    def test_bad_input(self):
        with self.assertRaises(gen.GenError):
            gen.row_for(card("X9", tribes=["GNOME"]))
        with self.assertRaises(gen.GenError):
            gen.row_for(card("X10", tier=7))


class Output(unittest.TestCase):
    def test_selection_and_header(self):
        ds = dataset(card("A"), card("T", role="token", slice="15A"), card("S", role="token", type="SPELL"),
                     card("O", role="token", slice=None), card("H", role="hero"))
        text = gen.build_inc(ds)
        self.assertTrue(text.startswith("// GENERATED by tools/battlegrounds/gen_bg_cpp.py"))
        self.assertIn("Do not edit by hand", text)
        rows = [line for line in text.splitlines() if line.startswith("        {")]
        self.assertEqual(len(rows), 3)             # the pool minion, the 15A token and the 15A spell
        self.assertIn("1 pool minions, 1 tokens and 1 spell cards", text)

    def test_duplicate_id_fails(self):
        with self.assertRaises(gen.GenError):
            gen.build_inc(dataset(card("A"), card("A")))

    def test_byte_stable_and_check_mode(self):
        ds = dataset(card("A"), card("B", tribes=["BEAST"]))
        self.assertEqual(gen.build_inc(ds), gen.build_inc(ds))
        with tempfile.TemporaryDirectory() as tmp, contextlib.redirect_stdout(io.StringIO()), \
                contextlib.redirect_stderr(io.StringIO()):
            data = Path(tmp) / "bg.json"
            out = Path(tmp) / "out.inc"
            hero_out = Path(tmp) / "out_hero.inc"
            quest_out = Path(tmp) / "out_quest.inc"
            reward_out = Path(tmp) / "out_reward.inc"
            import json
            data.write_text(json.dumps(ds), encoding="utf-8")
            # every --*-out is passed, so gen_bg_cpp.py never writes a repository .inc from a test run
            def gen_main(*extra):
                return gen.main(["--data", str(data), "--out", str(out), "--hero-out", str(hero_out),
                                 "--quest-out", str(quest_out), "--reward-out", str(reward_out)] + list(extra))
            self.assertEqual(gen_main("--check"), 1)   # missing files
            self.assertEqual(gen_main(), 0)
            self.assertEqual(gen_main("--check"), 0)
            out.write_bytes(out.read_bytes() + b"// edit\n")
            self.assertEqual(gen_main("--check"), 1)
            self.assertEqual(gen.main(["--data", str(Path(tmp) / "missing.json"), "--out", str(out),
                                       "--hero-out", str(hero_out), "--quest-out", str(quest_out),
                                       "--reward-out", str(reward_out)]), 2)
            self.assertNotIn(b"\r", out.read_bytes() if gen_main() == 0 else b"")


class QuestRows(unittest.TestCase):
    def test_quest_and_reward_rows(self):
        ds = dataset(
            {"id": "BG24_Quest_112", "dbf_id": 89641, "name": "Q", "role": "quest", "text": "..{0}.."},
            {"id": "BG24_Quest_318", "dbf_id": 89052, "name": "Q2", "role": "quest", "text": "..{0}.."},
            {"id": "BG24_Reward_107", "dbf_id": 89449, "name": "R", "role": "quest_reward", "text": "R"})
        values = {"quests": {"BG24_Quest_112": {"progress": 10, "in_pool": True},
                             "BG24_Quest_318": {"progress": 8, "in_pool": False}},
                  "rewards": {"BG24_Reward_107": {"in_pool": True}}}
        qtext, rtext = gen.build_quest_inc(ds, values)
        self.assertIn('        {"BG24_Quest_112", 89641, 10, true},', qtext)
        self.assertIn('        {"BG24_Quest_318", 89052, 8, false},', qtext)
        self.assertIn('        {"BG24_Reward_107", 89449, true},', rtext)
        self.assertIn("2 quests of the dataset", qtext)
        self.assertIn("1 in pool", qtext)
        self.assertIn("1 quest rewards", rtext)

    def test_missing_values_fail(self):
        ds = dataset({"id": "BG24_Quest_112", "dbf_id": 89641, "name": "Q", "role": "quest", "text": "..{0}.."},
                     {"id": "BG24_Reward_107", "dbf_id": 89449, "name": "R", "role": "quest_reward", "text": "R"})
        with self.assertRaises(gen.GenError):                       # quest not in quest_values.json
            gen.build_quest_inc(ds, {"quests": {}, "rewards": {"BG24_Reward_107": {"in_pool": True}}})
        with self.assertRaises(gen.GenError):                       # reward not in quest_values.json
            gen.build_quest_inc(ds, {"quests": {"BG24_Quest_112": {"progress": 10, "in_pool": True}}, "rewards": {}})
        with self.assertRaises(gen.GenError):                       # bad progress
            gen.build_quest_inc(ds, {"quests": {"BG24_Quest_112": {"progress": -1, "in_pool": True}},
                                    "rewards": {"BG24_Reward_107": {"in_pool": True}}})
        # an extra row in quest_values.json (a card later removed from the dataset) is harmless, not an error
        qtext, rtext = gen.build_quest_inc(ds, {"quests": {"BG24_Quest_112": {"progress": 10, "in_pool": True},
                                                          "BG24_Quest_999": {"progress": 1, "in_pool": True}},
                                               "rewards": {"BG24_Reward_107": {"in_pool": True}}})
        self.assertNotIn("BG24_Quest_999", qtext)


@unittest.skipUnless(bglib.NORMALIZED_PATH.is_file(), "bg.normalized.json missing (run import_bg.py)")
class RealDataset(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.ds = bglib.load_dataset()
        cls.text = gen.build_inc(cls.ds)
        cls.rows = [line for line in cls.text.splitlines() if line.startswith("        {")]

    def test_counts(self):
        self.assertEqual(len(self.rows), 167 + 21 + 51)   # 5d: Cobra, Snake, 10 Secrets; 5e: the 29 Darkmoon Prizes
        self.assertEqual(sum(1 for r in self.rows if "CardRole::Token" in r), 21)
        self.assertEqual(sum(1 for r in self.rows if "CardRole::Spell" in r), 51)
        self.assertEqual(sum(1 for r in self.rows if r.endswith("true, CardRole::Pool},")), 167)

    def test_stats_only(self):
        # no names or text: every quoted string is a card id
        for row in self.rows:
            for s in re.findall(r'"([^"]*)"', row):
                self.assertRegex(s, r"^[A-Za-z0-9_]*$")
        self.assertNotIn("Sewer Rat", self.text)

    def test_known_rows(self):
        rat = next(r for r in self.rows if r.startswith('        {"BG19_010",'))
        self.assertEqual(rat, '        {"BG19_010", 70790, 2, 3, 2, kTribeBeast, 0, "BG19_010_G", 70801, 6, 4, 0, true, CardRole::Pool},')
        half = next(r for r in self.rows if r.startswith('        {"BG19_010t",'))
        self.assertIn("kTribeBeast, kKwTaunt,", half)       # Taunt from the text, the data lists no mechanic
        zapp = next(r for r in self.rows if r.startswith('        {"BGS_022",'))
        self.assertIn(", 0, kKwWindfury, \"TB_BaconUps_091\"", zapp)  # Windfury only in the text and referenced tags
        self.assertIn("kKwWindfury, true, CardRole::Pool", zapp)   # its golden too (render override)

    def test_keyword_totals(self):
        self.assertEqual(sum(1 for r in self.rows if "kKwMagnetic" in r), 3)    # the 3 Magnetic Mechs
        self.assertEqual(sum(1 for r in self.rows if "kKwMegaWindfury" in r), 1)   # golden Zapp keeps Windfury
        self.assertEqual(sum(1 for r in self.rows if re.search(r"kKwWindfury", r)), 4)

    def test_committed_file_matches(self):
        self.assertTrue(gen.INC_PATH.is_file(), "run gen_bg_cpp.py")
        self.assertEqual(gen.INC_PATH.read_bytes(), self.text.encode("utf-8"))

    def test_quest_and_reward_table(self):
        values = gen._quest_values()
        qtext, rtext = gen.build_quest_inc(self.ds, values)
        qrows = [line for line in qtext.splitlines() if line.startswith("        {")]
        rrows = [line for line in rtext.splitlines() if line.startswith("        {")]
        self.assertEqual(len(qrows), 15)                              # the 15 dataset quests
        self.assertEqual(sum(1 for r in qrows if r.endswith(", true},")), 12)   # the 12 live quests
        self.assertEqual(len(rrows), 35)
        self.assertEqual(sum(1 for r in rrows if r.endswith(", true},")), 23)   # the 23 live rewards
        self.assertIn('        {"BG24_Quest_313", 89037, 7, true},', qtext)
        self.assertIn('        {"BG24_Reward_130", 90917, true},', rtext)
        self.assertTrue(gen.QUEST_INC_PATH.is_file(), "run gen_bg_cpp.py")
        self.assertEqual(gen.QUEST_INC_PATH.read_bytes(), qtext.encode("utf-8"))
        self.assertEqual(gen.REWARD_INC_PATH.read_bytes(), rtext.encode("utf-8"))


if __name__ == "__main__":
    unittest.main()
