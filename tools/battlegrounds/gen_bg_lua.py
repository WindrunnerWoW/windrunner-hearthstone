#!/usr/bin/env python3
"""Generates addon/Hearthstone/Battlegrounds/BgCardDB.lua (the addon's Battlegrounds card table).

Usage (from the repository root, modules/mod-hearthstone):
    python -I tools/battlegrounds/gen_bg_lua.py            # write addon/Hearthstone/Battlegrounds/BgCardDB.lua
    python -I tools/battlegrounds/gen_bg_lua.py --check    # do not write; exit 1 if the file differs from a fresh build

Reads data/battlegrounds/bg.normalized.json (through bglib) and data/battlegrounds/hero_armor.json (the 15C curated
hero list and armor tiers). Deterministic. The output is the tooltip and art
side of the engine's card table (src/battlegrounds/HsBgCardData.inc, generated by gen_bg_cpp.py): the same selection
in the same order (all 167 pool minions, then the included minion tokens), but with the names and text the server
never needs.

The output is a Lua 5.0 chunk (WoW 1.12): a single global table ``HS_BgCardDB``. It only uses double-quoted strings
with the escapes \\\\ \\" \\n \\r and 3-digit decimal \\ddd (Lua 5.0 has no \\x and no \\z), no long strings, no '#',
no varargs.

Per card: ``dbf`` id, ``name``, ``text`` (client markup, see display_text), ``tier`` 1-6, ``atk``/``hp``, ``kw`` (the
keyword names to show as icons), ``tribes`` (the data's race names, ``ALL`` for Nightmare Amalgam), ``golden`` (the
golden card's id, only on a normal card) and ``token`` 1 on a token. A golden card also gets ``g = 1`` and its own
stats/text/keywords, so a golden minion can be rendered from ``cards[cards[id].golden]``.

Besides ``cards`` the table holds ``heroes`` (the curated 15C/15E heroes keyed by card id: ``name``, ``health``,
``armor`` tier and ``power`` id) and ``powers`` (their hero powers and the extra powers of ``extra_powers``: ``name``,
``cost`` and ``text``), so the addon can look a hero or a hero power up by the id the server sends on the wire. It also
holds ``quests`` (the ``name``, ``text`` with the ``{0}`` number filled, ``number`` and ``pool``) and
``rewards`` (the quest rewards: ``name``, ``text``, ``pool``), keyed by id, from data/battlegrounds/quest_values.json.

Text transform (``display_text``): the same as the addon CardDB (tools/carddata/gen_addon_carddb.py) - <b>..</b> is WoW
gold, <i>..</i> light grey, other tags are dropped, typographic quotes/dashes become ASCII, ``$n``/``#n`` markers lose
their ``$``/``#``, blanks collapse and empty lines are dropped. A literal ``|`` is doubled to ``||``.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bglib  # noqa: E402

OUT_PATH = bglib.REPO_ROOT / "addon" / "Hearthstone" / "Battlegrounds" / "BgCardDB.lua"
ARMOR_PATH = bglib.DATA_DIR / "hero_armor.json"
QUEST_VALUES_PATH = bglib.DATA_DIR / "quest_values.json"

# The source leaves some reward / quest text placeholders for the game to fill. The addon text gets a readable
# fallback here; the runtime value, where there is one, is what the server sends on the wire instead. The quest `{0}`
# is the progress number (filled from the table for every quest).
PLACEHOLDER_FALLBACK = {
    "BG24_Reward_130": {"{0}": "Lightfang Enforcer"},
    "BG24_Reward_134": {"{0}": "minions of one of the game's minion types"},
    "BG24_Quest_151": {"{2}": "minions of one of two types", "{3}": "minions of the other"},
}
PLACEHOLDER_RE = re.compile(r"\{\d+\}")

BOLD_OPEN = "|cffffd100"
ITALIC_OPEN = "|cffb8b8b8"
COLOR_CLOSE = "|r"

# Keyword names shown as icons, in the order the engine lists them (HsBgTypes.h). Mega-Windfury is what a golden
# Windfury becomes (its text says so), so it is its own name.
KEYWORD_ORDER = ("TAUNT", "DIVINE_SHIELD", "POISONOUS", "WINDFURY", "MEGA_WINDFURY", "REBORN", "MAGNETIC", "VENOMOUS")

# The data's mechanics the client shows as a keyword icon (MODULAR is Magnetic).
MECHANIC_KEYWORD = {
    "TAUNT": "TAUNT", "DIVINE_SHIELD": "DIVINE_SHIELD", "POISONOUS": "POISONOUS", "WINDFURY": "WINDFURY",
    "REBORN": "REBORN", "MODULAR": "MAGNETIC", "MAGNETIC": "MAGNETIC", "VENOMOUS": "VENOMOUS",
}
# The data misses some keywords a card text STARTS with (see gen_bg_cpp.py). The same rule keeps the two tables honest.
TEXT_KEYWORDS = {"Taunt": "TAUNT", "Divine Shield": "DIVINE_SHIELD", "Poisonous": "POISONOUS", "Venomous": "VENOMOUS", "Reborn": "REBORN",
                 "Windfury": "WINDFURY"}
LEADING_KEYWORDS = re.compile(r"^(?:(?:<b>)+(?:Taunt|Divine Shield|Poisonous|Venomous|Reborn|Mega-Windfury|Windfury)"
                              r"(?:</b>)+[,.\s]*(?:</b>)*)+")

_TYPOGRAPHY = {
    "\u2018": "'", "\u2019": "'", "\u201a": "'", "\u201b": "'",
    "\u201c": '"', "\u201d": '"', "\u201e": '"',
    "\u2013": "-", "\u2014": "-", "\u2212": "-",
    "\u2026": "...", "\u00a0": " ",
}
_BOLD_RE = re.compile(r"<b>(.*?)</b>", re.S)
_ITALIC_RE = re.compile(r"<i>(.*?)</i>", re.S)
_TAG_RE = re.compile(r"</?[a-zA-Z][^>]*>")
_MARKER_RE = re.compile(r"[$#](\d+)")


class GenError(Exception):
    pass


def display_text(raw) -> str:
    """Convert the dataset markup to client display text (see the module docstring)."""
    if not raw:
        return ""
    t = raw.replace("[x]", "").replace("\r", "")
    t = t.replace("|", "||")
    for src, dst in _TYPOGRAPHY.items():
        t = t.replace(src, dst)
    t = _MARKER_RE.sub(r"\1", t)
    t = _BOLD_RE.sub(lambda m: BOLD_OPEN + m.group(1) + COLOR_CLOSE, t)
    t = _ITALIC_RE.sub(lambda m: ITALIC_OPEN + m.group(1) + COLOR_CLOSE, t)
    t = _TAG_RE.sub("", t)
    lines = [re.sub(r"[ \t]+", " ", line).strip() for line in t.split("\n")]
    return "\n".join(line for line in lines if line)


def lua_str(value: str) -> str:
    """Quote ``value`` as a Lua 5.0 double-quoted string (ASCII output only)."""
    out = ['"']
    for ch in value:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif 0x20 <= o < 0x7F:
            out.append(ch)
        else:
            out.extend("\\%03d" % b for b in ch.encode("utf-8"))
    out.append('"')
    return "".join(out)


def text_keywords(text) -> list:
    """Mechanics named by the keywords a text starts with (same rule as gen_bg_cpp.py)."""
    m = LEADING_KEYWORDS.match((text or "").replace("[x]", ""))
    if not m:
        return []
    return [TEXT_KEYWORDS[k] for k in re.findall(r">(Taunt|Divine Shield|Poisonous|Venomous|Reborn|Windfury)<", m.group(0))]


def keywords(mechanics, text, golden: bool) -> list:
    """Keyword icon names of one card, in KEYWORD_ORDER. A golden Windfury is Mega-Windfury when its text says so."""
    names = []
    for m in list(mechanics) + text_keywords(text):
        if m == "WINDFURY":
            if golden and "Mega-Windfury" in (text or ""):
                names.append("MEGA_WINDFURY")
            else:
                names.append("WINDFURY")
        elif m in MECHANIC_KEYWORD:
            names.append(MECHANIC_KEYWORD[m])
    return sorted(set(names), key=KEYWORD_ORDER.index)


def included(card: dict) -> bool:
    """The same selection as the engine's card table (gen_bg_cpp.py)."""
    return card["role"] == "pool_minion" or (
        card["role"] == "token" and card["type"] in ("MINION", "SPELL") and card["slice"] == "15A")


def _fields(card: dict, *, golden: bool, token: bool) -> list:
    spell = card["type"] == "SPELL"
    tier = card["tier"]
    if not isinstance(tier, int) or (0 if spell else 1) > tier or tier > 6:
        raise GenError(f"{card['id']}: tier {tier!r} out of range")
    fields = [
        f"dbf={card['dbf_id']}",
        f"name={lua_str(display_text(card['name']))}",
    ]
    text = display_text(card["text"])
    if text:
        fields.append(f"text={lua_str(text)}")
    fields.append(f"tier={tier}")
    if spell:
        fields.append("spell=1")
    else:
        fields.append(f"atk={card['attack']}")
        fields.append(f"hp={card['health']}")
    kw = keywords(card["mechanics"], card["text"], golden) if not spell else []
    if kw:
        fields.append("kw={" + ",".join(lua_str(k) for k in kw) + "}")
    if card["tribes"]:
        fields.append("tribes={" + ",".join(lua_str(t) for t in card["tribes"]) + "}")
    if golden:
        fields.append("g=1")
    if token and not spell:
        fields.append("token=1")
    return fields


def card_entries(card: dict) -> list:
    """The (id, entry) pairs of one normal card and its golden twin (if it has one)."""
    token = card["role"] == "token"
    entries = []
    normal = _fields(card, golden=False, token=token)
    g = card["golden"]
    if g:
        normal.append(f"golden={lua_str(g['id'])}")
        golden = {"id": g["id"], "dbf_id": g["dbf_id"], "name": card["name"], "type": card["type"],
                  "tier": card["tier"], "attack": g["attack"], "health": g["health"], "mechanics": g["mechanics"],
                  "text": g["text"], "tribes": card["tribes"], "role": card["role"]}
        entries.append((g["id"], _fields(golden, golden=True, token=token)))
    entries.append((card["id"], normal))
    return entries


def load_armor(path=None) -> dict:
    """The 15C curated hero list and armor tiers (data/battlegrounds/hero_armor.json)."""
    return json.loads(Path(path or ARMOR_PATH).read_text(encoding="utf-8"))


def load_quest_values(path=None) -> dict:
    """The 15D quest progress numbers and the 24.2 offer list (data/battlegrounds/quest_values.json)."""
    return json.loads(Path(path or QUEST_VALUES_PATH).read_text(encoding="utf-8"))


def fill_text(card_id: str, raw, number: int = 0) -> str:
    """Display text with the placeholders the source left (the quest number and the fallbacks above) filled."""
    t = (raw or "").replace("{0}", str(number)) if number else (raw or "")
    for src, dst in PLACEHOLDER_FALLBACK.get(card_id, {}).items():
        t = t.replace(src, dst)
    return display_text(PLACEHOLDER_RE.sub("?", t))


def quest_entries(dataset: dict, values: dict) -> list:
    """The (id, [fields]) rows of the 15D quests, id sorted: name, text (number filled), number, pool."""
    vq = values["quests"]
    rows = []
    for c in sorted((c for c in dataset["cards"] if c["role"] == "quest"), key=lambda c: c["id"]):
        v = vq.get(c["id"])
        if v is None:
            raise GenError(f"quest_values.json is missing {c['id']}")
        number = v.get("progress", 0)
        fields = [f"dbf={c['dbf_id']}", f"name={lua_str(display_text(c['name']))}",
                  f"text={lua_str(fill_text(c['id'], c['text'], number))}", f"number={number}"]
        if v["in_pool"]:
            fields.append("pool=1")
        rows.append((c["id"], fields))
    return rows


def reward_entries(dataset: dict, values: dict) -> list:
    """The (id, [fields]) rows of the 15D quest rewards, id sorted: name, text, pool."""
    vr = values["rewards"]
    rows = []
    for c in sorted((c for c in dataset["cards"] if c["role"] == "quest_reward"), key=lambda c: c["id"]):
        v = vr.get(c["id"])
        if v is None:
            raise GenError(f"quest_values.json is missing {c['id']}")
        fields = [f"dbf={c['dbf_id']}", f"name={lua_str(display_text(c['name']))}",
                  f"text={lua_str(fill_text(c['id'], c['text']))}"]
        if v["in_pool"]:
            fields.append("pool=1")
        rows.append((c["id"], fields))
    return rows


def hero_entries(dataset: dict, armor: dict) -> tuple:
    """The (hero rows, power rows) of the curated 15C/15E heroes, in the curated order, and the extra powers.

    A hero row is (hero id, [fields]): name, health (40 when the data has none, as gen_bg_cpp.py) and armor tier from
    ``armor``, the hero power id. A power row is (power id, [fields]): name, cost and text. Both come from the dataset
    (roles ``hero`` and ``hero_power``). ``armor["extra_powers"]`` adds the powers a hero can take on (Galewing's
    flightpaths, Tavish's aims, Bru'kan's invocations, Ragnaros's Sulfuras), which the addon shows when one becomes the
    current power or a power choice offers them. A curated hero that is not in the dataset is skipped, so a synthetic
    dataset renders empty blocks.
    """
    tiers = armor["armor_tier"]
    missing = [hid for hid in armor["curated"] if hid not in tiers]
    if missing:
        raise GenError(f"curated hero not in the armor table: {sorted(missing)}")
    by_id = {c["id"]: c for c in dataset["cards"]}

    def power_fields(pid: str) -> list:
        power = by_id.get(pid)
        if power is None or power["role"] != "hero_power":
            raise GenError(f"power {pid} is not a hero power")
        cost = power.get("cost")
        if not isinstance(cost, int) or cost < 0:
            cost = 0
        fields = [f"name={lua_str(display_text(power['name']))}", f"cost={cost}"]
        text = display_text(power["text"])
        if text:
            fields.append(f"text={lua_str(text)}")
        return fields

    hero_rows, power_rows, seen = [], [], set()
    for hid in armor["curated"]:
        hero = by_id.get(hid)
        if hero is None:
            continue
        health = hero.get("health")
        if not isinstance(health, int) or health <= 0:
            health = 40                              # a hero without data starts at 40 (as gen_bg_cpp.py)
        pid = hero.get("hero_power") or ""
        if not pid:
            raise GenError(f"hero {hid} has no hero power")
        if pid not in by_id or by_id[pid]["role"] != "hero_power":
            raise GenError(f"hero {hid}: power {pid} is not a hero power")
        hero_rows.append((hid, [f"name={lua_str(display_text(hero['name']))}", f"health={health}",
                                f"armor={tiers[hid]}", f"power={lua_str(pid)}"]))
        if pid in seen:
            continue
        seen.add(pid)
        power_rows.append((pid, power_fields(pid)))
    for pid in armor.get("extra_powers", []):
        if pid in seen:
            continue
        power = by_id.get(pid)
        if power is None or power["role"] != "hero_power":
            continue                                 # a synthetic dataset of a test: as a missing hero, skipped
        seen.add(pid)
        power_rows.append((pid, power_fields(pid)))
    return hero_rows, power_rows


# Cariel Roame's Conviction improvements (render pass): choices of a power choice with no card in the pinned
# data, named here for the addon (the engine knows them as kStance* in HsBgHeroes.h). (id, name, text)
SYNTHETIC_POWERS = (
    ("BG21_HERO_000p_united", "United Stance", "Buffs one additional" + chr(10) + "friendly minion."),
    ("BG21_HERO_000p_offense", "Offensive Stance", "Adds +2 Attack to each" + chr(10) + "Hero Power buff."),
    ("BG21_HERO_000p_defense", "Defensive Stance", "Adds +2 Health to each" + chr(10) + "Hero Power buff."),
)


def render(dataset: dict, armor=None, values=None) -> str:
    cards = [c for c in dataset["cards"] if included(c)]
    ids = [c["id"] for c in cards]
    if len(set(ids)) != len(ids):
        raise GenError("duplicate card id")
    if armor is None:
        armor = load_armor()
    if values is None:
        values = load_quest_values()
    hero_rows, power_rows = hero_entries(dataset, armor)
    owner_known = any(c["id"] == "BG21_HERO_000p" for c in dataset["cards"])   # a synthetic test dataset has no Cariel
    for pid, name, text in (SYNTHETIC_POWERS if owner_known else ()):
        power_rows.append((pid, [f"name={lua_str(name)}", "cost=0", f"text={lua_str(text)}"]))
    quest_rows = quest_entries(dataset, values)
    reward_rows = reward_entries(dataset, values)
    rows = []
    for c in cards:
        rows.extend(card_entries(c))
    entry_ids = [i for i, _ in rows]
    if len(set(entry_ids)) != len(entry_ids):
        raise GenError("duplicate card or golden id")
    pool = sum(1 for c in cards if c["role"] == "pool_minion")
    spells = sum(1 for c in cards if c["type"] == "SPELL")
    token_count = len(cards) - pool
    checksum = bglib.content_hash([[i, e] for i, e in rows])
    lines = [
        "-- GENERATED by tools/battlegrounds/gen_bg_lua.py from data/battlegrounds/bg.normalized.json.",
        "-- Do not edit by hand: run `python tools/setup_all.py` after the Battlegrounds dataset changes.",
        "-- Lua 5.0 (WoW 1.12). Card text uses WoW color codes (|cffffd100 keyword, |cffb8b8b8 reminder, |r).",
        f"-- {pool} pool minions, {token_count - spells} minion tokens and {spells} spells, plus their golden twins ({len(rows)} entries).",
        f"-- {len(hero_rows)} curated 15C heroes and their {len(power_rows)} hero powers, from data/battlegrounds/hero_armor.json.",
        f"-- {len(quest_rows)} 15D quests and {len(reward_rows)} quest rewards, from data/battlegrounds/quest_values.json.",
        f"-- Entry check sha256 {checksum}.",
        "",
        "HS_BgCardDB = {",
        f"    datasetId = {lua_str(dataset['dataset_id'])},",
        f"    hash = {lua_str(dataset['content_hash'][:16])},",
        f"    fullHash = {lua_str(dataset['content_hash'])},",
        f"    schema = {dataset['schema_version']},",
        f"    count = {len(rows)},",
        f"    poolCount = {pool},",
        f"    tokenCount = {token_count},",
        f"    heroCount = {len(hero_rows)},",
        f"    powerCount = {len(power_rows)},",
        f"    questCount = {len(quest_rows)},",
        f"    rewardCount = {len(reward_rows)},",
        "    cards = {",
    ]
    for card_id, entry in rows:
        lines.append(f"        [{lua_str(card_id)}] = {{ {', '.join(entry)} }},")
    lines.append("    },")
    lines.append("    heroes = {")
    for hero_id, entry in hero_rows:
        lines.append(f"        [{lua_str(hero_id)}] = {{ {', '.join(entry)} }},")
    lines.append("    },")
    lines.append("    powers = {")
    for power_id, entry in power_rows:
        lines.append(f"        [{lua_str(power_id)}] = {{ {', '.join(entry)} }},")
    lines.append("    },")
    lines.append("    quests = {")
    for quest_id, entry in quest_rows:
        lines.append(f"        [{lua_str(quest_id)}] = {{ {', '.join(entry)} }},")
    lines.append("    },")
    lines.append("    rewards = {")
    for reward_id, entry in reward_rows:
        lines.append(f"        [{lua_str(reward_id)}] = {{ {', '.join(entry)} }},")
    lines.append("    },")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if the file differs from a fresh build")
    ap.add_argument("--data", type=Path, default=bglib.NORMALIZED_PATH, help="the normalized dataset to read")
    ap.add_argument("--out", type=Path, default=OUT_PATH, help="the .lua file to write or check")
    args = ap.parse_args(argv)
    try:
        dataset = json.loads(args.data.read_text(encoding="utf-8"))
        text = render(dataset)
    except (OSError, ValueError, KeyError, GenError, TypeError) as exc:
        print(f"GENERATE FAILED: {exc} (run tools/battlegrounds/import_bg.py first?)", file=sys.stderr)
        return 2
    data = text.encode("utf-8")
    if args.check:
        if not args.out.is_file() or args.out.read_bytes() != data:
            print(f"CHECK FAILED: {args.out} is missing or differs from a fresh build", file=sys.stderr)
            return 1
        print(f"check ok: {args.out} matches a fresh build")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(data)
    print(f"wrote {args.out} ({len(data)} bytes, {text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
