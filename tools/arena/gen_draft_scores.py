#!/usr/bin/env python3
"""Generates src/arena/HsArenaDraftScores.inc from data/decks/deck_library.json (draft AI).

For every class C, the card value is how often the card appears in the library and starter decks of that class
(copies summed over the decks), scaled to 0..100 so the most used card of that class (class cards and neutrals
combined) is 100. A neutral card therefore gets one score per class it appears in. Cards never seen in a class are
not listed; the C++ side applies its own fallback from mana cost and stats. Opponent and quest NPC decks are not
counted.

    python tools/arena/gen_draft_scores.py            write the include file
    python tools/arena/gen_draft_scores.py --check    exit 1 when the include file is not what the generator produces

Output: one line per entry, sorted by class, then card id:  { "DRUID", "CS2_005", 87 },
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
INPUT = os.path.join(ROOT, "data", "decks", "deck_library.json")
OUT = os.path.join(ROOT, "src", "arena", "HsArenaDraftScores.inc")

CLASSES = ["DRUID", "HUNTER", "MAGE", "PALADIN", "PRIEST", "ROGUE", "SHAMAN", "WARLOCK", "WARRIOR"]
COUNTED_KINDS = ("library", "starter")
TOP = 100


def count_copies(doc):
    """Returns {class: {card id: copies}} over the counted decks."""
    counts = {c: {} for c in CLASSES}
    for deck in doc["decks"]:
        if deck.get("kind") not in COUNTED_KINDS:
            continue
        cls = deck.get("class")
        if cls not in counts:
            raise ValueError("deck %r has unknown class %r" % (deck.get("key"), cls))
        for card, n in deck["cards"].items():
            if not isinstance(n, int) or isinstance(n, bool) or n < 1:
                raise ValueError("deck %r: bad copy count for %s" % (deck.get("key"), card))
            counts[cls][card] = counts[cls].get(card, 0) + n
    return counts


def scores(counts):
    """Returns [(class, card id, score)] sorted by class then card id; scores are integers in 1..100."""
    out = []
    for cls in CLASSES:
        per = counts[cls]
        if not per:
            raise ValueError("class %s has no counted decks" % cls)
        top = max(per.values())
        for card in sorted(per):
            # integer division with rounding half up; a seen card never drops to 0
            s = max(1, (per[card] * TOP + top // 2) // top)
            out.append((cls, card, s))
    return out


HEADER = """// Generated by tools/arena/gen_draft_scores.py from data/decks/deck_library.json. Do not edit by hand.
// Draft AI card values per class, 0..100: copies in the library and starter decks of the class, scaled so the
// most used card of that class (class cards and neutrals together) is 100. Cards not listed were never seen.
// Entries: { class, card id, score }, sorted by class then card id.
"""


def render(entries):
    lines = [HEADER]
    for cls, card, s in entries:
        lines.append('{ "%s", "%s", %d },\n' % (cls, card, s))
    return "".join(lines)


def generate(raw):
    """raw: bytes of deck_library.json. Returns the include file text."""
    doc = json.loads(raw.decode("utf-8"))
    return render(scores(count_copies(doc)))


def read_text(path):
    try:
        with open(path, "rb") as f:
            return f.read().decode("utf-8").replace("\r\n", "\n")
    except FileNotFoundError:
        return None


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when the include file is stale")
    args = ap.parse_args(argv)
    with open(INPUT, "rb") as f:
        text = generate(f.read())
    if args.check:
        if read_text(OUT) != text:
            print("STALE: %s (run python tools/arena/gen_draft_scores.py)" % os.path.relpath(OUT, ROOT))
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d entries)" % (os.path.relpath(OUT, ROOT), text.count("\n") - HEADER.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
