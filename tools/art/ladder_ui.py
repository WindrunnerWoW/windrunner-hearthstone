#!/usr/bin/env python3
"""Build the owner's ladder background, rank badges, Legend gem and stars for WoW 1.12.

Run tools/art/.venv/Scripts/python tools/art/ladder_ui.py.
deploy-addon.ps1 copies the BLPs. Optional rank_16.png .. rank_25.png are picked up when supplied.
Sources: art/source/ui/ladder/ranks. No generated artwork.
"""
import os
from PIL import Image
import artlib as A
from ui_icons import write_blp, crop_opaque, scale_premultiplied

WIDTH, HEIGHT, TILE = 1536, 896, 512
CROP = (24, 22, 1504, 882)


def build_ranks():
    src = os.path.join(A.ART, "source", "ui", "ladder", "ranks")
    entries = {}
    for rank in range(1, 26):
        path = os.path.join(src, "rank_%d.png" % rank)
        if os.path.exists(path):
            entries[rank] = build_icon(path, "LadderRank_%d" % rank, 256)
    legend = build_icon(os.path.join(src, "legend.png"), "LadderLegend", 256)
    # Normalize both stars to a square canvas so filled and empty shapes share their visual size.
    for state in ("full", "empty"):
        path = os.path.join(src, "star_%s.png" % state)
        with Image.open(path) as image:
            image = crop_opaque(image.convert("RGBA"))
        image = scale_premultiplied(image, (60, round(60 * image.height / image.width)))
        canvas = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
        canvas.alpha_composite(image, ((64-image.width)//2, (64-image.height)//2))
        write_blp("LadderStar_" + state, canvas)
    lines = ["-- Generated by tools/art/ladder_ui.py from the owner's rank artwork.",
             "-- Ranks without supplied artwork use the numbered plate in LadderUI.lua.",
             "HS_LadderRankTextures = { maxRank = 25, ranks = {"]
    for rank, e in sorted(entries.items()):
        lines.append("    [%d] = { right = %.8f, bottom = %.8f, aspect = %.8f }," % (rank, *e))
    lines.extend(["}, legend = { right = %.8f, bottom = %.8f, aspect = %.8f } }" % legend, ""])
    with open(os.path.join(A.ROOT, "addon", "Hearthstone", "LadderRankTextures.lua"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def build_icon(path, name, side):
    with Image.open(path) as im:
        im = crop_opaque(im.convert("RGBA"))
    aspect = im.width / im.height
    if aspect <= 1:
        w, h = round(side * aspect), side
    else:
        w, h = side, round(side / aspect)
    im = scale_premultiplied(im, (w, h))
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.alpha_composite(im, (0, 0))
    write_blp(name, canvas)
    return w / side, h / side, aspect


def main():
    path = os.path.join(A.ART, "source", "ui", "ladder", "background.png")
    with Image.open(path) as src:
        if src.size != (1536, 1024):
            raise SystemExit("Expected the owner's 1536 x 1024 ladder background")
        # The source has a black margin and rounded black corners; crop to the stone frame and stretch back to the
        # layout size (the dialog border drawn by LadderUI covers the cut edge).
        im = src.convert("RGBA").crop(CROP).resize((WIDTH, HEIGHT), Image.LANCZOS)
    for row in range(2):
        for col in range(3):
            piece = im.crop((col * TILE, row * TILE, (col + 1) * TILE, min((row + 1) * TILE, HEIGHT)))
            canvas = Image.new("RGBA", (TILE, TILE), (0, 0, 0, 255))
            canvas.paste(piece, (0, 0))
            write_blp("LadderBg_c%dr%d" % (col, row), canvas)
    build_ranks()


if __name__ == "__main__":
    main()
