#!/usr/bin/env python3
"""Build the icy blue Done and Choose plates for WoW 1.12.

Run tools/art/.venv/Scripts/python tools/art/button_ui.py.
Sources: art/source/ui/buttons/done.png, choose.png, show.png, hide.png and choose_one.png (the Choose One scroll
banner of the match chooser). Writes art/out/UI/ButtonDone.blp, ButtonChoose.blp, ButtonShow.blp, ButtonHide.blp and
ChooseBanner.blp and PageArrow.blp (the book edge page arrow, pointing right; 512 x 256, the art fitted and centred with a little transparent margin) and
addon/Hearthstone/ButtonTextures.lua, which CollectionUI.Piece("btn_done" / "btn_choose" / ...) reads.
deploy-addon.ps1 copies the BLPs.
"""
import os
from PIL import Image, ImageFilter
import artlib as A
from ui_icons import write_blp, scale_premultiplied

W, H, MARGIN = 512, 256, 6
PLATES = (("btn_done", "done.png", "ButtonDone"), ("btn_choose", "choose.png", "ButtonChoose"),
          ("btn_show", "show.png", "ButtonShow"), ("btn_hide", "hide.png", "ButtonHide"),
          ("choose_banner", "choose_one.png", "ChooseBanner"),
          ("page_arrow", "page_arrow.png", "PageArrow"),
          ("deck_limit", "deck_limit.png", "DeckLimit"),
          ("deck_limit_1", "deck_limit_1.png", "DeckLimit1"))


def build(src_name, out_name):
    with Image.open(os.path.join(A.ART, "source", "ui", "buttons", src_name)) as im:
        im = im.convert("RGBA")
    # a strict threshold: the sources carry faint specks of glow far outside the plate
    box = im.getchannel("A").point(lambda a: 255 if a > 128 else 0).getbbox()
    im = im.crop(box)
    k = min((W - 2 * MARGIN) / im.width, (H - 2 * MARGIN) / im.height)
    im = scale_premultiplied(im, (round(im.width * k), round(im.height * k)))
    canvas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    canvas.alpha_composite(im, ((W - im.width) // 2, (H - im.height) // 2))
    write_blp(out_name, canvas)


def build_glow():
    """A soft icy halo in the shape of the plate: the plate fills the middle half of the canvas, so the glow
    texture is drawn at twice the size of the button and the halo has room to fade out."""
    with Image.open(os.path.join(A.ART, "source", "ui", "buttons", "choose.png")) as im:
        im = im.convert("RGBA")
    im = im.crop(im.getchannel("A").point(lambda a: 255 if a > 128 else 0).getbbox())
    k = min((W / 2 - MARGIN) / im.width, (H / 2 - MARGIN) / im.height)
    im = im.resize((round(im.width * k), round(im.height * k)), Image.LANCZOS)
    mask = Image.new("L", (W, H), 0)
    mask.paste(im.getchannel("A"), ((W - im.width) // 2, (H - im.height) // 2))
    near = mask.filter(ImageFilter.GaussianBlur(9))
    far = mask.filter(ImageFilter.GaussianBlur(26))
    alpha = Image.eval(Image.blend(near, far, 0.55), lambda v: min(255, round(v * 1.9)))
    canvas = Image.new("RGBA", (W, H), (110, 200, 255, 0))
    canvas.putalpha(alpha)
    write_blp("ButtonGlow", canvas)


def main():
    lines = ["-- Generated by tools/art/button_ui.py from the owner's Done and Choose artwork.",
             "-- CollectionUI.Piece(name) answers from this table before the collection sheet's pieces.",
             "HS_ButtonTextures = {"]
    for piece, src, out in PLATES:
        build(src, out)
        bs = chr(92) * 2    # a doubled backslash inside the Lua string
        path = bs.join(["Interface", "Hearthstone", "Textures", "UI", out])
        lines.append('    %s = { path = "%s", right = 1, bottom = 1 },' % (piece, path))
    build_glow()
    path = bs.join(["Interface", "Hearthstone", "Textures", "UI", "ButtonGlow"])
    lines.append('    btn_glow = { path = "%s", right = 1, bottom = 1 },' % path)
    lines.extend(["}", ""])
    with open(os.path.join(A.ROOT, "addon", "Hearthstone", "ButtonTextures.lua"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


if __name__ == "__main__":
    main()
