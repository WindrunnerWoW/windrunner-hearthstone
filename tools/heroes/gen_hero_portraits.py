"""Generate the hero portrait catalog (addon Lua and server rows) from data/heroes/portraits.json."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'data/heroes/portraits.json'
LUA = ROOT / 'addon/Hearthstone/HeroPortraits.lua'
ROWS = ROOT / 'src/heroes/HsHeroRows.inc'
CLASSES = 'DRUID HUNTER MAGE PALADIN PRIEST ROGUE SHAMAN WARLOCK WARRIOR'.split()
BAD_NAME_CHARS = ('"', chr(92), chr(10), chr(13), chr(0))  # names go into Lua and C++ string literals
ID = re.compile(r'^[A-Za-z0-9_]{1,32}$')  # fits hearthstone_hero_portrait.portrait_id VARCHAR(32)


def generate(data):
    classes = data['classes']
    assert sorted(classes) == CLASSES, 'every class, nothing else'
    seen = set()
    total = 0
    for cls in CLASSES:
        entries = classes[cls]
        assert [e['default'] for e in entries].count(True) == 1 and entries[0]['default'], \
            cls + ': the default portrait comes first and is the only default'
        for e in entries:
            cid = e['card_id']
            assert ID.match(cid), 'bad portrait id ' + cid
            assert cid.lower() not in seen, 'duplicate portrait id ' + cid
            seen.add(cid.lower())
            assert e['name'].strip() and not any(c in e['name'] for c in BAD_NAME_CHARS), 'bad name for ' + cid
            total += 1
    assert data['count'] == total, 'count is %d, catalog has %d' % (data['count'], total)
    lua = ['-- Generated by tools/heroes/gen_hero_portraits.py from data/heroes/portraits.json. Do not edit.',
           '-- Per class: the default portrait first, then the alternatives that Legend #1 credits can unlock.',
           'HearthstoneHeroPortraits = {']
    rows = ['// Generated by tools/heroes/gen_hero_portraits.py. Class, portrait id, name, is default.']
    for cls in CLASSES:
        lua.append('    %s = {' % cls)
        for e in classes[cls]:
            lua.append('        { id = "%s", name = "%s", default = %s },' % (
                e['card_id'], e['name'], 'true' if e['default'] else 'false'))
            rows.append('    {"%s", "%s", "%s", %s},' % (cls, e['card_id'], e['name'],
                                                         'true' if e['default'] else 'false'))
        lua.append('    },')
    lua.append('}')
    return '\n'.join(lua) + '\n', '\n'.join(rows) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = generate(json.loads(SOURCE.read_text(encoding='utf-8-sig')))
    for path, content in zip((LUA, ROWS), outputs):
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit('Stale generated file: ' + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
